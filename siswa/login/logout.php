<?php

/*
|--------------------------------------------------------------------------
| SIMU
|--------------------------------------------------------------------------
| Logout Siswa
|--------------------------------------------------------------------------
*/

session_start();

/*
|--------------------------------------------------------------------------
| Pastikan Session Siswa Ada
|--------------------------------------------------------------------------
*/

if (!isset($_SESSION['siswa'])) {

    header("Location: login.php");
    exit;

}

/*
|--------------------------------------------------------------------------
| Hapus Session Siswa
|--------------------------------------------------------------------------
*/

unset($_SESSION['siswa']);

/*
|--------------------------------------------------------------------------
| Bersihkan Flash Message Lama
|--------------------------------------------------------------------------
*/

unset($_SESSION['warna']);
unset($_SESSION['pesan']);

/*
|--------------------------------------------------------------------------
| Flash Message
|--------------------------------------------------------------------------
*/

$_SESSION['warna'] = "success";

$_SESSION['pesan'] = "Anda berhasil keluar dari sistem.";

/*
|--------------------------------------------------------------------------
| Redirect ke Login
|--------------------------------------------------------------------------
*/

header("Location: login.php");

exit;

?>

