<?php

/*
|--------------------------------------------------------------------------
| SIMU
|--------------------------------------------------------------------------
| AJAX Selesai Ujian
|--------------------------------------------------------------------------
*/

session_start();

require_once "../../../../app/database/database.php";

header('Content-Type: application/json');


/*
|--------------------------------------------------------------------------
| Validasi Login Siswa
|--------------------------------------------------------------------------
*/

if (!isset($_SESSION['siswa'])) {

    echo json_encode([
        'status' => false,
        'pesan' => 'Sesi login telah berakhir.'
    ]);

    exit;
}


/*
|--------------------------------------------------------------------------
| Validasi Request
|--------------------------------------------------------------------------
*/

if ($_SERVER['REQUEST_METHOD'] !== 'POST') {

    echo json_encode([
        'status' => false,
        'pesan' => 'Metode request tidak diizinkan.'
    ]);

    exit;
}


/*
|--------------------------------------------------------------------------
| Data Siswa
|--------------------------------------------------------------------------
*/

$id_siswa = (int) $_SESSION['siswa']['id_siswa'];


/*
|--------------------------------------------------------------------------
| Data Yang Dikirim
|--------------------------------------------------------------------------
*/

$id_sesi = isset($_POST['id_sesi'])
    ? (int) $_POST['id_sesi']
    : 0;

$id_ujian = isset($_POST['id_ujian'])
    ? (int) $_POST['id_ujian']
    : 0;


/*
|--------------------------------------------------------------------------
| Validasi Data
|--------------------------------------------------------------------------
*/

if ($id_sesi <= 0 || $id_ujian <= 0) {

    echo json_encode([
        'status' => false,
        'pesan' => 'Data ujian tidak lengkap.'
    ]);

    exit;
}